"use client";

// Project-context knowledge graph (requirements, components, agents, tasks,
// decisions, versions) built from persisted relationships — not AI guesses.

import { Background, Controls, MarkerType, ReactFlow, type Edge, type Node } from "@xyflow/react";
import "@xyflow/react/dist/style.css";
import { useMemo } from "react";
import type { State } from "../client";

export type GNode = { id: string; kind: string; label: string; data: unknown };

const COLORS: Record<string, { bg: string; border: string }> = {
  requirement: { bg: "#eef2ff", border: "#6366f1" },
  frontend: { bg: "#ecfeff", border: "#0891b2" },
  design: { bg: "#fdf4ff", border: "#c026d3" },
  backend: { bg: "#f0fdf4", border: "#16a34a" },
  testing: { bg: "#fffbeb", border: "#d97706" },
  agent: { bg: "#f5f3ff", border: "#7c3aed" },
  task: { bg: "#f8fafc", border: "#94a3b8" },
  decision: { bg: "#fff1f2", border: "#e11d48" },
  version: { bg: "#ecfdf5", border: "#059669" },
};

export function buildGraph(s: State, opts: { tasks?: boolean; decisions?: boolean } = {}) {
  const nodes: GNode[] = [];
  const edges: { s: string; t: string; label: string; dashed?: boolean }[] = [];
  const approved = s.requirements.filter((r) => r.status === "approved");
  for (const r of approved) nodes.push({ id: `req:${r.key}`, kind: "requirement", label: `${r.key} · ${r.title}`, data: r });
  for (const c of s.components) nodes.push({ id: `comp:${c.key}`, kind: c.category, label: c.name, data: c });
  for (const d of s.reqDeps) edges.push({ s: `req:${d.fromKey}`, t: `req:${d.toKey}`, label: "depends on" });
  for (const d of s.compDeps) edges.push({ s: `comp:${d.fromKey}`, t: `comp:${d.toKey}`, label: "depends on" });
  for (const r of approved) for (const c of r.components) if (s.components.some((x) => x.key === c)) edges.push({ s: `comp:${c}`, t: `req:${r.key}`, label: "implements" });

  if (opts.tasks !== false) {
    for (const a of s.agents) nodes.push({ id: `agent:${a.id}`, kind: "agent", label: a.name, data: a });
    for (const t of s.tasks.slice(0, 10)) {
      nodes.push({ id: `task:${t.id}`, kind: "task", label: `${t.title} (${t.status})`, data: t });
      edges.push({ s: `task:${t.id}`, t: `agent:${t.agentId}`, label: "belongs to" });
    }
  }
  if (opts.decisions !== false) {
    const decisions = s.decisions.slice(-8);
    for (const d of decisions) {
      nodes.push({ id: `dec:${d.id}`, kind: "decision", label: d.title, data: d });
      for (const k of d.affectedRequirements) if (approved.some((r) => r.key === k)) edges.push({ s: `req:${k}`, t: `dec:${d.id}`, label: "modified by" });
    }
    for (const v of s.versions) {
      nodes.push({ id: `ver:${v.id}`, kind: "version", label: `Artifact v${v.number}`, data: v });
      if (v.decisionId && decisions.some((d) => d.id === v.decisionId)) edges.push({ s: `ver:${v.id}`, t: `dec:${v.decisionId}`, label: "approved by" });
      if (v.derivedFromId) edges.push({ s: `ver:${v.id}`, t: `ver:${v.derivedFromId}`, label: "derived from", dashed: true });
    }
    if (opts.tasks !== false) {
      for (const t of s.tasks.slice(0, 10)) {
        if (t.status === "quarantined") {
          const d = [...decisions].reverse().find((x) => x.kind === "change" && x.affectedRequirements.some((k) => t.requirementKeys.includes(k)));
          if (d) edges.push({ s: `dec:${d.id}`, t: `task:${t.id}`, label: "invalidates", dashed: true });
        }
        const v = s.versions.find((x) => x.decisionId && s.decisions.find((d) => d.id === x.decisionId)?.proposedById === t.agentId && t.type === "build" && t.status === "completed");
        if (v && t.type === "build") edges.push({ s: `ver:${v.id}`, t: `task:${t.id}`, label: "generated by", dashed: true });
      }
    }
  }
  return { nodes, edges };
}

const COLUMN: Record<string, number> = { requirement: 0, frontend: 1, design: 2, backend: 2, testing: 2, task: 3, agent: 4, decision: 4, version: 5 };

export function ContextGraph({
  state,
  highlight,
  dim,
  onSelect,
  height = 560,
  opts,
}: {
  state: State;
  highlight?: Set<string>;
  dim?: boolean;
  onSelect?: (n: GNode) => void;
  height?: number;
  opts?: { tasks?: boolean; decisions?: boolean };
}) {
  const { nodes, edges } = useMemo(() => buildGraph(state, opts), [state, opts]);
  const rf = useMemo(() => {
    const rows: Record<number, number> = {};
    const order = ["requirement", "frontend", "design", "backend", "testing", "task", "agent", "decision", "version"];
    const sorted = [...nodes].sort((a, b) => order.indexOf(a.kind) - order.indexOf(b.kind));
    const rfNodes: Node[] = sorted.map((n) => {
      const col = COLUMN[n.kind] ?? 2;
      const row = (rows[col] = (rows[col] ?? -1) + 1);
      const c = COLORS[n.kind] ?? COLORS.task;
      const hot = highlight?.has(n.id);
      return {
        id: n.id,
        position: { x: col * 260, y: row * 58 },
        data: { label: n.label, g: n },
        style: {
          background: hot ? "#fef3c7" : c.bg,
          border: `${hot ? 2.5 : 1.5}px solid ${hot ? "#f59e0b" : c.border}`,
          borderRadius: 10,
          fontSize: 11,
          width: 220,
          padding: "6px 8px",
          opacity: dim && highlight && !hot ? 0.35 : 1,
          boxShadow: hot ? "0 0 0 4px rgba(245,158,11,0.2)" : undefined,
        },
      };
    });
    const ids = new Set(rfNodes.map((n) => n.id));
    const rfEdges: Edge[] = edges
      .filter((e) => ids.has(e.s) && ids.has(e.t))
      .map((e, i) => {
        const hot = highlight?.has(e.s) && highlight?.has(e.t);
        return {
          id: `e${i}`,
          source: e.s,
          target: e.t,
          label: e.label,
          labelStyle: { fontSize: 9, fill: "#64748b" },
          style: { stroke: hot ? "#f59e0b" : e.label === "invalidates" ? "#e11d48" : "#cbd5e1", strokeWidth: hot ? 2 : 1, strokeDasharray: e.dashed ? "4 3" : undefined, opacity: dim && highlight && !hot ? 0.25 : 1 },
          markerEnd: { type: MarkerType.ArrowClosed, color: hot ? "#f59e0b" : "#94a3b8" },
        };
      });
    return { rfNodes, rfEdges };
  }, [nodes, edges, highlight, dim]);

  return (
    <div style={{ height }} className="rounded-xl border border-slate-200 bg-white">
      <ReactFlow nodes={rf.rfNodes} edges={rf.rfEdges} fitView fitViewOptions={{ padding: 0.05 }} minZoom={0.2} onNodeClick={(_, n) => onSelect?.((n.data as { g: GNode }).g)} proOptions={{ hideAttribution: true }} nodesConnectable={false}>
        <Background gap={18} color="#eef2f7" />
        <Controls showInteractive={false} />
      </ReactFlow>
    </div>
  );
}

export function Legend() {
  return (
    <div className="flex flex-wrap gap-2 text-[11px] text-slate-600">
      {Object.entries(COLORS).map(([k, c]) => (
        <span key={k} className="flex items-center gap-1"><span className="h-3 w-3 rounded" style={{ background: c.bg, border: `1.5px solid ${c.border}` }} />{k}</span>
      ))}
    </div>
  );
}
